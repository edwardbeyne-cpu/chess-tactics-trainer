#!/usr/bin/env node
/**
 * Rebuild data/lichess-puzzles.ts from the full Lichess puzzle database.
 *
 * Usage:
 *   curl -L -o /tmp/lichess_db_puzzle.csv.zst https://database.lichess.org/lichess_db_puzzle.csv.zst
 *   zstd -dc /tmp/lichess_db_puzzle.csv.zst | node scripts/build-puzzle-cache.js
 *
 * CSV columns:
 *   PuzzleId,FEN,Moves,Rating,RatingDeviation,Popularity,NbPlays,Themes,GameUrl,OpeningTags
 *
 * Selection: for each trained theme, fill a quota per 100-point rating band
 * across 600–2600 so every playing strength has depth (the old cache had
 * only 166 puzzles above 2100 total).
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const THEMES = [
  'fork', 'pin', 'skewer', 'discoveredAttack', 'backRankMate', 'smotheredMate',
  'deflection', 'interference', 'overloading', 'zugzwang', 'attraction', 'clearance',
  'trappedPiece', 'doubleCheck', 'discoveredCheck', 'kingsideAttack', 'queensideAttack',
];

const MIN_RATING = 600;
const MAX_RATING = 2600;
const BAND_SIZE = 100;
const QUOTA_PER_BAND = 45;
const MAX_RD = 100;       // rating deviation — well-established ratings only
const MIN_PLAYS = 200;    // enough plays that the rating is trustworthy
const MIN_POPULARITY = 70;

const NUM_BANDS = (MAX_RATING - MIN_RATING) / BAND_SIZE;

// Lichess has no "overloading" tag — its closest concept is capturingDefender
// (remove/overload the defender). Map it so the app's overloading drills work.
const TAG_ALIASES = { capturingDefender: 'overloading' };

// byTheme[theme][bandIndex] = puzzles
const byTheme = {};
for (const t of THEMES) {
  byTheme[t] = Array.from({ length: NUM_BANDS }, () => []);
}
const themeSet = new Set(THEMES);

let processed = 0;
let kept = 0;
let headerSkipped = false;

const rl = readline.createInterface({ input: process.stdin, terminal: false });

rl.on('line', (line) => {
  if (!headerSkipped) { headerSkipped = true; return; }
  processed++;

  // Fast pre-parse: split only what we need. No commas inside the first 8 columns.
  const parts = line.split(',');
  if (parts.length < 8) return;
  const [id, fen, moves, ratingStr, rdStr, popStr, playsStr, themesStr] = parts;

  const rating = Number(ratingStr);
  if (!Number.isFinite(rating) || rating < MIN_RATING || rating >= MAX_RATING) return;
  if (Number(rdStr) > MAX_RD) return;
  if (Number(playsStr) < MIN_PLAYS) return;
  if (Number(popStr) < MIN_POPULARITY) return;

  const themes = themesStr.split(' ');
  const band = Math.floor((rating - MIN_RATING) / BAND_SIZE);

  // A puzzle may appear under every trained theme it carries — selection-time
  // dedupe (usedIds in generateMasterySet) prevents duplicates within a set.
  let placed = false;
  for (const rawTag of themes) {
    const t = TAG_ALIASES[rawTag] ?? rawTag;
    if (!themeSet.has(t)) continue;
    const bucket = byTheme[t][band];
    if (bucket.length >= QUOTA_PER_BAND) continue;
    bucket.push({ id, fen, moves: moves.split(' '), rating, themes });
    placed = true;
  }
  if (placed) kept++;
});

rl.on('close', () => {
  const out = [];
  out.push('// AUTO-GENERATED by scripts/build-puzzle-cache.js — do not edit by hand.');
  out.push('// Source: https://database.lichess.org/ puzzle dump.');
  out.push('// NEVER import this file at a module top level — always use');
  out.push('// `await import("@/data/lichess-puzzles")` inside async functions.');
  out.push('');
  out.push('export interface LichessCachedPuzzle {');
  out.push('  id: string;');
  out.push('  fen: string;        // Position BEFORE the opponent\'s setup move (moves[0])');
  out.push('  moves: string[];    // UCI moves; moves[0] is the opponent\'s move, moves[1] is the first solution move');
  out.push('  rating: number;');
  out.push('  themes: string[];');
  out.push('}');
  out.push('');

  let maxPerPattern = 0;
  const themeChunks = [];
  for (const t of THEMES) {
    const puzzles = byTheme[t].flat().sort((a, b) => a.rating - b.rating);
    maxPerPattern = Math.max(maxPerPattern, puzzles.length);
    const lines = puzzles.map((p) =>
      `    { id: ${JSON.stringify(p.id)}, fen: ${JSON.stringify(p.fen)}, moves: ${JSON.stringify(p.moves)}, rating: ${p.rating}, themes: ${JSON.stringify(p.themes)} },`
    );
    themeChunks.push(`  ${JSON.stringify(t)}: [\n${lines.join('\n')}\n  ],`);
  }

  out.push(`export const PUZZLES_PER_PATTERN = ${maxPerPattern};`);
  out.push('');
  out.push('export const PATTERN_PUZZLE_COUNTS: Record<string, number> = {');
  for (const t of THEMES) {
    out.push(`  ${JSON.stringify(t)}: ${byTheme[t].flat().length},`);
  }
  out.push('};');
  out.push('');
  out.push('export const cachedPuzzlesByTheme: Record<string, LichessCachedPuzzle[]> = {');
  out.push(themeChunks.join('\n'));
  out.push('};');
  out.push('');

  const dest = path.join(__dirname, '../data/lichess-puzzles.ts');
  fs.writeFileSync(dest, out.join('\n'));

  const perTheme = THEMES.map((t) => `${t}: ${byTheme[t].flat().length}`).join(', ');
  const total = THEMES.reduce((s, t) => s + byTheme[t].flat().length, 0);
  console.error(`Processed ${processed} rows, kept ${kept}.`);
  console.error(`Per theme: ${perTheme}`);
  console.error(`Total: ${total} puzzles → ${dest}`);
});
